def detect_allergens_in_text(text: str) -> list[str]:
    text_lower = text.lower()
    found = []
    for allergen, keywords in KOREAN_ALLERGENS.items():
        for keyword in keywords:
            if keyword in text_lower:
                found.append(allergen)
                break
    return found
